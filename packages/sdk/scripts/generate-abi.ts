#!/usr/bin/env bun
/**
 * generate-abi.ts — build-only Node/Bun script
 *
 * Reads Foundry artifact JSON, emits:
 *   packages/sdk/src/generated/factory-abi.ts   — typed const ABI
 *   packages/sdk/src/generated/agreement-abi.ts — typed const ABI
 *   packages/sdk/src/generated/provenance.ts    — source/sha256 manifest
 *
 * NEVER run at browser runtime. This script runs only at build time.
 * The generated .ts files have NO node: imports; they are safe for Vite.
 *
 * Drift check: re-running this script produces identical output when artifacts
 * are unchanged. CI can assert `git diff --exit-code` after running it.
 */

import { createHash } from "node:crypto";
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, "..", "..", "..");
const OUT_DIR   = resolve(__dirname, "..", "src", "generated");

mkdirSync(OUT_DIR, { recursive: true });

type ArtifactEntry = {
  name:       string;
  label:      string;
  sourcePath: string;
};

const ARTIFACTS: ArtifactEntry[] = [
  {
    name:       "NoticeVaultFactory",
    label:      "factory",
    sourcePath: "contracts/out/NoticeVaultFactory.sol/NoticeVaultFactory.json",
  },
  {
    name:       "NoticeVaultAgreement",
    label:      "agreement",
    sourcePath: "contracts/out/NoticeVaultAgreement.sol/NoticeVaultAgreement.json",
  },
];

// ── Conformance lists (must match spec) ────────────────────────────────────────

const REQUIRED_FACTORY: string[] = [
  "createAgreement","invalidateNonce","isNonceUnavailable","outstandingLiability",
  "factoryCap","agreementCap","allocatedCapacity","perAgreementAllocation","token","registeredAgreement","setCreationPaused",
  "AgreementCreated","NonceInvalidated","CapacityChanged","CreationPauseChanged",
];
const REQUIRED_AGREEMENT: string[] = [
  "fundNextPeriod","startNotice","materializeNotice","claimProvider","claimClientRefund",
  "preview","terms","accounting","factory","client","provider",
  "RegularFunded","NoticeStarted","ProviderClaimed","ClientRefunded",
];

function assertConformance(abi: unknown[], required: string[], label: string): void {
  const names = new Set(abi.map((e: unknown) => (e as Record<string,unknown>)["name"] as string));
  for (const req of required) {
    if (!names.has(req))
      throw new Error(`ABI conformance failure: ${label} missing entry "${req}"`);
  }
}

const provenanceEntries: string[] = [];

for (const artifact of ARTIFACTS) {
  const absPath = resolve(REPO_ROOT, artifact.sourcePath);
  const raw = readFileSync(absPath);
  const sha256 = createHash("sha256").update(raw).digest("hex");
  const parsed = JSON.parse(raw.toString()) as { abi: unknown[]; metadata?: { compiler?: { version?: string } } };
  const abi = parsed.abi;

  // Conformance check
  const required = artifact.label === "factory" ? REQUIRED_FACTORY : REQUIRED_AGREEMENT;
  assertConformance(abi, required, artifact.name);

  const count = abi.length;
  const varName = artifact.label === "factory" ? "FACTORY_ABI" : "AGREEMENT_ABI";
  const typeName = artifact.label === "factory" ? "NoticeVaultFactoryAbi" : "NoticeVaultAgreementAbi";

  const outPath = resolve(OUT_DIR, `${artifact.label}-abi.ts`);
  const content = `\
/**
 * @noticevault/sdk — generated ABI module (DO NOT EDIT)
 *
 * Generated by: packages/sdk/scripts/generate-abi.ts
 * Source artifact: ${artifact.sourcePath}
 * Contract: ${artifact.name}
 * Entry count: ${count}
 * SHA-256: ${sha256}
 *
 * This file has NO Node.js imports and is safe for browser/Vite bundling.
 * Re-generate with: bun run packages/sdk/scripts/generate-abi.ts
 */

export type ${typeName} = typeof ${varName};

export const ${varName} = ${JSON.stringify(abi, null, 2)} as const;
`;

  writeFileSync(outPath, content, "utf-8");
  console.log(`  wrote ${artifact.label}-abi.ts (${count} entries, sha256=${sha256.slice(0,16)}...)`);

  provenanceEntries.push(`
  ${artifact.label}: {
    contractName: ${JSON.stringify(artifact.name)},
    source:       ${JSON.stringify(artifact.sourcePath)},
    sha256:       ${JSON.stringify(sha256)},
    entryCount:   ${count},
  },`);
}

// ── Write provenance manifest ──────────────────────────────────────────────────

const provenancePath = resolve(OUT_DIR, "provenance.ts");
const provenanceContent = `\
/**
 * @noticevault/sdk — generated ABI provenance manifest (DO NOT EDIT)
 *
 * Generated by: packages/sdk/scripts/generate-abi.ts
 * Records source paths and SHA-256 digests of the Foundry artifacts used.
 *
 * This file has NO Node.js imports and is safe for browser/Vite bundling.
 * Re-generate with: bun run packages/sdk/scripts/generate-abi.ts
 */

export const ABI_PROVENANCE = {${provenanceEntries.join("")}
} as const;

export type AbiProvenance = typeof ABI_PROVENANCE;
`;

writeFileSync(provenancePath, provenanceContent, "utf-8");
console.log(`  wrote provenance.ts`);
console.log("generate-abi: done");
